// Tabla de verdad - Operadores logios con booleand
// && (AND)  
// Todas las condiciones tiene que ser verdaderas para que el resultado sea verdadero.

console.log(true && true)  // Verdadero
console.log(true && false)  // False
console.log(false && true)  // False
console.log(false && false)  // False

// || (OR)
// Una de las condiciones tiene que ser verdadera para que el resultado sea verdadero.

console.log(true || true)  // Verdadero
console.log(true || false)  // Verdadero
console.log(false || true)  // Verdadero
console.log(false || false)  // False

// ! (NOT)
// Invierte valoor
console.log(!(true))   //Siendo true, el resultado es false 
console.log(!(false))  //Siendo false, el resultado es true